"""Seed search by lattice reduction, for any set of measured letters.

The RNG is affine, so the state after character i's rand is s_i = a_i * x + c_i (mod 2^31),
where x is the state after the pivot character's rand. Each measured velocity bounds a rand,
and a rand is bits 16..30 of a state. Differences to the pivot cancel the shared velocity
bias, so with y_i = s_i - x = (a_i - 1) * x + c_i (mod 2^31):

    x   in [ (r_p - span_p) * 2^16,  (r_p + span_p + 1) * 2^16 )        (pivot's own rand)
    y_i in [ (D_i - T_i - 1) * 2^16, (D_i + T_i + 1) * 2^16 )            (each other character)

where D_i is the measured rand difference and T_i its tolerance (the +-1 covers the borrow
between the two truncated values). The vectors (x, y_2, ..., y_n) for all x form the lattice
generated by (1, a_2 - 1, ..., a_n - 1) and 2^31 * e_i, shifted by (0, c_2, ..., c_n). So the
seeds that fit are the lattice points in a box.

This follows the idea of CaveGen's Seed.java (digit sequences, Matthew's LLL), generalised:
the characters can be any subset, so the basis is built and reduced per sublevel instead of
precomputed. After LLL the box's points are enumerated with Fincke-Pohst inside the ball
around the box (coordinates scaled so the box is a cube), then checked exactly.

The work depends on how many seeds the box can hold, not on 2^31: with 5+ good letters it is
usually just the true seed; with 3 it can be thousands. Either way it takes milliseconds.
"""

from __future__ import annotations

import math

import numpy as np

from .. import rng
from .search import V_PER_RAND, Candidate, _score

M = 1 << 31
UNIT = 1 << 16


def lll(basis: list[list[int]], delta: float = 0.99) -> list[list[int]]:
    """LLL-reduce integer row vectors (exact integer rows, floating Gram-Schmidt).

    Entries here stay below ~2^47, well inside a double's precision, and the dimension is
    small (one row per measured character), so recomputing Gram-Schmidt after each change
    is cheap and keeps it simple."""
    b = [list(map(int, row)) for row in basis]
    n = len(b)

    def gs():
        bs = [[float(x) for x in row] for row in b]
        mu = [[0.0] * n for _ in range(n)]
        nb = [0.0] * n
        for i in range(n):
            for j in range(i):
                mu[i][j] = sum(p * q for p, q in zip(b[i], bs[j])) / nb[j] if nb[j] else 0.0
                bs[i] = [p - mu[i][j] * q for p, q in zip(bs[i], bs[j])]
            nb[i] = sum(p * p for p in bs[i])
        return mu, nb

    mu, nb = gs()
    k = 1
    while k < n:
        for j in range(k - 1, -1, -1):
            q = round(mu[k][j])
            if q:
                b[k] = [p - q * r for p, r in zip(b[k], b[j])]
                # size reduction leaves the Gram-Schmidt vectors alone; only row k's mu changes
                for t in range(j):
                    mu[k][t] -= q * mu[j][t]
                mu[k][j] -= q
        if nb[k] >= (delta - mu[k][k - 1] ** 2) * nb[k - 1]:
            k += 1
        else:
            b[k], b[k - 1] = b[k - 1], b[k]
            mu, nb = gs()
            k = max(k - 1, 1)
    return b


def box_points(gens: list[list[int]], lo: list[int], hi: list[int], max_nodes: int = 2_000_000) -> list[list[int]] | None:
    """All points of the lattice spanned by integer rows `gens` with lo <= p <= hi (inclusive),
    or None if the search would visit more than `max_nodes` nodes."""
    n = len(lo)
    half = [(h - l) / 2 for l, h in zip(lo, hi)]
    wmax = max(half)
    # integer column scales that make the box roughly a cube (they only affect reduction quality)
    k = [max(1, round(wmax / max(h, 1))) for h in half]
    scaled = [[x * kj for x, kj in zip(row, k)] for row in gens]
    red = lll(scaled)
    basis = [[x // kj for x, kj in zip(row, k)] for row in red]     # exact: columns scale back
    # Gram-Schmidt of the scaled reduced basis
    bf = [[float(x) for x in row] for row in red]
    bs, mu, nb = [], [[0.0] * n for _ in range(n)], []
    for i in range(n):
        v = bf[i][:]
        for j in range(i):
            mu[i][j] = sum(p * q for p, q in zip(bf[i], bs[j])) / nb[j]
            v = [p - mu[i][j] * q for p, q in zip(v, bs[j])]
        bs.append(v)
        nb.append(sum(p * p for p in v))
    center = [(l + h) / 2 * kj for l, h, kj in zip(lo, hi, k)]
    tau = [sum(p * q for p, q in zip(center, bs[i])) / nb[i] for i in range(n)]
    r2 = sum((h * kj) ** 2 for h, kj in zip(half, k)) * (1 + 1e-9) + 1.0

    out: list[list[int]] = []
    coef = [0] * n
    nodes = 0

    def rec(i: int, rem: float) -> bool:
        nonlocal nodes
        c = tau[i] - sum(coef[j] * mu[j][i] for j in range(i + 1, n))
        w = math.sqrt(max(rem, 0.0) / nb[i])
        for ci in range(math.ceil(c - w), math.floor(c + w) + 1):
            nodes += 1
            if nodes > max_nodes:
                return False
            coef[i] = ci
            d = rem - (ci - c) ** 2 * nb[i]
            if i == 0:
                p = [sum(coef[j] * basis[j][t] for j in range(n)) for t in range(n)]
                if all(l <= x <= h for x, l, h in zip(p, lo, hi)):
                    out.append(p)
            elif not rec(i - 1, d):
                return False
        return True

    return out if rec(n - 1, r2) else None


def search(v: np.ndarray, sigma: np.ndarray, k_tol: float = 4.0, max_bias: float = 0.5, cap: float = 16.0,
           top: int = 5, leave_out=(), max_nodes: int = 2_000_000,
           max_dim: int = 8) -> list[Candidate]:
    """Same inputs and output as search.search, by lattice enumeration.

    `leave_out`: characters to ignore (to step around one mistracked letter)."""
    v = np.asarray(v, dtype=np.float64)
    sigma = np.asarray(sigma, dtype=np.float64)
    measured = [i for i in range(len(v)) if np.isfinite(v[i]) and np.isfinite(sigma[i]) and i not in set(np.atleast_1d(leave_out).tolist())]
    if len(measured) < 3:
        raise ValueError("need at least 3 measured characters")
    if rng.active() == "switch":
        return _search64(v, sigma, measured, k_tol, max_bias, cap, top, max_nodes)
    pivot = min(measured, key=lambda i: sigma[i])
    others = [i for i in measured if i != pivot
              and k_tol * math.hypot(sigma[i], sigma[pivot]) / V_PER_RAND < (1 << 13)]   # else no constraint
    if len(others) < 2:
        raise ValueError("need at least 3 usable characters")
    # the best few letters already pin the seed (each cuts the candidates ~50x); the rest only
    # add LLL work, and they still count in the score below
    others = sorted(others, key=lambda i: sigma[i])[:max_dim - 1]
    jumps = {i: rng.jump(i - pivot) for i in measured}

    span = (k_tol * sigma[pivot] + max_bias) / V_PER_RAND
    rp = v[pivot] / V_PER_RAND
    lo = [max(0, math.floor(rp - span)) * UNIT]
    hi = [min(1 << 15, math.ceil(rp + span) + 1) * UNIT - 1]
    gens = [[1] + [(jumps[i][0] - 1) % M for i in others]]
    for t in range(len(others)):
        row = [0] * (len(others) + 1)
        row[t + 1] = M
        gens.append(row)
    for i in others:
        d = (v[i] - v[pivot]) / V_PER_RAND
        tol = k_tol * math.hypot(sigma[i], sigma[pivot]) / V_PER_RAND
        c = jumps[i][1] % M
        lo.append(math.floor(d - tol - 1) * UNIT - c)
        hi.append(math.ceil(d + tol + 1) * UNIT - 1 - c)
    pts = box_points(gens, lo, hi, max_nodes)
    if not pts:
        return []
    states = np.array(sorted({p[0] % M for p in pts}), dtype=np.uint64)
    best = _score(states, v, sigma, measured, jumps, pivot, cap, max_bias)
    best.sort(key=lambda c: c.score)
    return best[:top]


SWITCH_MAX_DIM = 16


def _search64(v, sigma, measured, k_tol, max_bias, cap, top, max_nodes) -> list[Candidate]:
    """lattice.search for the Switch generator (64-bit musl LCG, speed = 5 * s / 2^64).

    Same box as the GC search, with the full 64-bit state instead of bits 0..30: the pivot's
    state is bounded by its speed (plus the allowed offset), every other letter's state
    difference to the pivot by the speed difference (the offset cancels). A 64-bit state needs
    more letters than a 31-bit one: about 12 good letters pin it; fewer usually leave too many
    states to enumerate, and the entry is left to chain.py's search near its neighbours."""
    m64 = rng.M64
    pivot = min(measured, key=lambda i: sigma[i])
    others = sorted((i for i in measured if i != pivot), key=lambda i: sigma[i])[:SWITCH_MAX_DIM - 1]
    jumps = {i: rng.jump(i - pivot) for i in measured}
    span = k_tol * sigma[pivot] + max_bias
    lo = [max(0, math.floor((v[pivot] - span) / 5 * m64))]
    hi = [min(m64 - 1, math.ceil((v[pivot] + span) / 5 * m64))]
    row = [1]
    for i in others:
        a, c = jumps[i]
        row.append((a - 1) % m64)
        d = v[i] - v[pivot]
        tol = k_tol * math.hypot(sigma[i], sigma[pivot]) + 1e-6
        lo.append(math.floor((d - tol) / 5 * m64) - c)
        hi.append(math.ceil((d + tol) / 5 * m64) - c)
    n = len(row)
    gens = [row] + [[m64 if j == t else 0 for j in range(n)] for t in range(1, n)]
    pts = box_points(gens, lo, hi, max_nodes)
    if not pts:
        return []
    states = np.array(sorted({p[0] % m64 for p in pts}), dtype=np.uint64)
    best = _score(states, v, sigma, measured, jumps, pivot, cap, max_bias)
    best.sort(key=lambda c: c.score)
    return best[:top]
